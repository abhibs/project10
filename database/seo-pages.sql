-- One record per route. '*' holds global site defaults.
-- NULL fields mean: use site defaults, then the metadata defined in code.
CREATE TABLE IF NOT EXISTS seo_pages (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  page_label VARCHAR(255) NOT NULL,
  route_path VARCHAR(255) NOT NULL,
  meta_title VARCHAR(255) DEFAULT NULL,
  meta_description TEXT DEFAULT NULL,
  focus_keywords TEXT DEFAULT NULL COMMENT 'Comma-separated editorial keywords',
  canonical_url VARCHAR(2048) DEFAULT NULL,
  og_title VARCHAR(255) DEFAULT NULL,
  og_description TEXT DEFAULT NULL,
  og_image VARCHAR(2048) DEFAULT NULL,
  og_type VARCHAR(50) DEFAULT NULL,
  og_site_name VARCHAR(255) DEFAULT NULL,
  og_locale VARCHAR(20) DEFAULT NULL,
  twitter_card ENUM('summary', 'summary_large_image', 'app', 'player') DEFAULT NULL,
  twitter_title VARCHAR(255) DEFAULT NULL,
  twitter_description TEXT DEFAULT NULL,
  twitter_image VARCHAR(2048) DEFAULT NULL,
  twitter_site VARCHAR(255) DEFAULT NULL,
  robots_index TINYINT(1) DEFAULT NULL,
  robots_follow TINYINT(1) DEFAULT NULL,
  robots_extra VARCHAR(255) DEFAULT NULL,
  structured_data JSON DEFAULT NULL COMMENT 'JSON-LD; validate before rendering',
  head_scripts MEDIUMTEXT DEFAULT NULL COMMENT 'Stored only; trusted admin content',
  body_start_scripts MEDIUMTEXT DEFAULT NULL,
  body_end_scripts MEDIUMTEXT DEFAULT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY seo_pages_route_unique (route_path)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
